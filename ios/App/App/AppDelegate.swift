    func application(_ application: UIApplication, didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]?) -> Bool {
        configureAudio()
        return true
    }

    /// Sesli anlatım uygulamanın özü: telefon sessize alınmışken de duyulmalı.
    /// `.playback` kategorisi yan taraftaki sessize alma düğmesini aşar; `.spokenAudio` ve
    /// `.duckOthers` ile arkada çalan müzik susturulmaz, sadece anlatım boyunca kısılır.
    private func configureAudio() {
        let session = AVAudioSession.sharedInstance()
        try? session.setCategory(.playback, mode: .spokenAudio, options: [.duckOthers])
        try? session.setActive(true)
    }

    func applicationDidBecomeActive(_ application: UIApplication) {
        // Telefon görüşmesi gibi kesintilerden sonra ses oturumunu geri aç.
        try? AVAudioSession.sharedInstance().setActive(true)
    }

